"""The 504 boundary mechanism, kept under test (V2 M1; gap analysis §6.11).

`scripts/m1_timeout_probe.py` reproduces the deployed shape

    browser -> CloudFront (origin_read_timeout 60s) -> ALB (idle_timeout 60s)
            -> Uvicorn (no request timeout) -> synchronous LLM/document work

at full scale. These tests run the same code at small values so the finding
stays protected without adding a minute to the gate.

The finding these protect, recorded in `docs/evidence/m1-timeout-inventory.md`:
past the gateway's read timeout the caller gets a **gateway-generated 504**, and
the origin carries on working unaware. That second half is why M3's `202`
contract is a correctness fix and not just a nicer error message — the work
behind an aborted request still completes, so a retrying user can drive it
twice.
"""

from __future__ import annotations

import asyncio
import json
import subprocess
import sys

import pytest

from scripts.m1_timeout_probe import _under_budget_control_delay, reproduce

# Scaled down from the deployed 60s. The mechanism is a comparison between two
# durations, so it reproduces identically at any scale.
GATEWAY_TIMEOUT = 0.75


def _run(**kwargs):
    return asyncio.run(reproduce(**kwargs))


def test_origin_inside_the_deadline_is_passed_through():
    """Control: the boundary only bites when the origin is actually too slow."""
    result = _run(gateway_timeout=GATEWAY_TIMEOUT, origin_delay=0.05)
    assert result.status == 200
    assert result.answered_by == "origin"
    assert result.client_elapsed < GATEWAY_TIMEOUT


def test_origin_past_the_deadline_yields_a_gateway_504():
    """The failing boundary: the gateway answers, not the application.

    This is the §6.11 question — the 504 is generated by the edge, so no
    application-side error handling, status code, or response body can change
    what the caller sees.
    """
    result = _run(gateway_timeout=GATEWAY_TIMEOUT, origin_delay=GATEWAY_TIMEOUT * 4)
    assert result.status == 504
    assert result.answered_by == "gateway"


def test_the_client_gives_up_at_the_gateway_deadline_not_the_origin_delay():
    """The caller waits the gateway's timeout, not the real duration of the
    work — which is why raising an application or SDK timeout cannot fix this.
    """
    origin_delay = GATEWAY_TIMEOUT * 4
    result = _run(gateway_timeout=GATEWAY_TIMEOUT, origin_delay=origin_delay)
    assert result.client_elapsed >= GATEWAY_TIMEOUT
    assert result.client_elapsed < origin_delay


def test_the_origin_keeps_working_after_the_504():
    """The part that makes this a correctness problem rather than a cosmetic
    one: the request was aborted, the work was not.

    A user who sees the 504 and retries an import or a generation runs it a
    second time while the first is still running. M3's durable `202` contract
    plus an idempotency key is the fix; a bigger timeout is not.
    """
    result = _run(gateway_timeout=GATEWAY_TIMEOUT, origin_delay=GATEWAY_TIMEOUT * 3)
    assert result.status == 504
    assert result.origin_completed is True, (
        "the synthetic origin should have finished its work despite the 504"
    )
    assert result.origin_elapsed >= GATEWAY_TIMEOUT


@pytest.mark.parametrize("multiplier", [2, 3, 5])
def test_boundary_holds_at_several_scales(multiplier):
    """The boundary is a duration comparison, so it must not depend on how far
    past the deadline the origin is — which is what licenses testing the
    deployed 60s behaviour at 0.75s."""
    result = _run(
        gateway_timeout=GATEWAY_TIMEOUT, origin_delay=GATEWAY_TIMEOUT * multiplier
    )
    assert result.status == 504
    assert result.answered_by == "gateway"


# ── --also-under-budget's control delay (M1-L-001) ──────────────────────────
# An earlier version used a flat max(0.5, gateway_timeout / 20), which broke
# for any gateway_timeout below 1s: at --gateway-timeout 0.2 the "control"
# delay came out to 0.5s -- itself past the deadline, so the control run came
# back as a 504 too, exactly like the case it was supposed to contrast with.

@pytest.mark.parametrize(
    "gateway_timeout", [0.05, 0.1, 0.2, 0.75, 1.0, 10.0, 60.0]
)
def test_under_budget_control_delay_always_fits_inside_the_timeout(gateway_timeout):
    assert _under_budget_control_delay(gateway_timeout) < gateway_timeout


def test_under_budget_control_delay_matches_the_recorded_evidence_run():
    """Pinned to the value docs/evidence/m1-timeout-inventory.md's recorded run
    used at the deployed 60s timeout (a 3.0s control), so a future change to
    this formula that would silently invalidate that evidence gets caught
    here."""
    assert _under_budget_control_delay(60.0) == pytest.approx(3.0)


def test_cli_also_under_budget_reproduces_the_reported_bug_is_now_fixed():
    """End-to-end reproduction of the exact command that exposed M1-L-001:
    `--gateway-timeout 0.2 --origin-delay 0.4 --also-under-budget` used to
    report a 504 for *both* results, including the control. Runs the real CLI
    as a subprocess rather than calling `reproduce()` directly, since the bug
    lived in `main()`'s argument handling, not in `reproduce()` itself — the
    committed unit tests already covered `reproduce()` and still passed while
    this was broken."""
    from pathlib import Path

    repo_root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        [
            sys.executable, "-m", "scripts.m1_timeout_probe",
            "--gateway-timeout", "0.2",
            "--origin-delay", "0.4",
            "--also-under-budget",
        ],
        capture_output=True,
        text=True,
        timeout=30,
        cwd=str(repo_root),
    )
    assert result.returncode == 0, result.stderr

    decoder = json.JSONDecoder()
    documents = []
    idx = 0
    text = result.stdout.strip()
    while idx < len(text):
        obj, idx = decoder.raw_decode(text, idx)
        documents.append(obj)
        while idx < len(text) and text[idx] in "\n\r\t ":
            idx += 1
    assert len(documents) == 2, result.stdout

    control, boundary = documents
    assert control["status"] == 200, control
    assert control["answered_by"] == "origin"
    assert boundary["status"] == 504
    assert boundary["answered_by"] == "gateway"


def test_probe_binds_only_loopback():
    """Evidence hygiene: the reproduction must stay local and non-persistent.

    Guards the safety claim in the probe's docstring, so a later edit cannot
    quietly turn an evidence script into something that talks to a real host.
    """
    from pathlib import Path

    source = Path(__file__).resolve().parents[1] / "scripts" / "m1_timeout_probe.py"
    text = source.read_text(encoding="utf-8")
    # Every bind/connect target is loopback.
    assert text.count('"127.0.0.1"') >= 3
    assert "0.0.0.0" not in text
    # No file, database, or credential access.
    for forbidden in ("open(", "boto3", "requests.", "os.environ", "DATABASE_URL"):
        assert forbidden not in text, f"probe should not use {forbidden!r}"
